// The service worker is generated with `registerType: 'prompt'`: a new build
// installs in the background and then waits, instead of taking over on its own
// and reloading the page under someone who is halfway through logging a dose.
// This module registers the worker, keeps checking for new builds while the
// app is open, and tells the UI when one is waiting. The page only reloads when
// the user taps the refresh button.
//
// Where there is no service worker at all (the dev server, the Tauri desktop
// app, a Docker install opened over plain http), registration fails or is
// skipped and the prompt simply never shows.

const UPDATE_CHECK_INTERVAL_MS = 30 * 60_000;
const MIN_CHECK_INTERVAL_MS = 60_000;

type Listener = () => void;

let updateReady = false;
let waitingWorker: ServiceWorker | null = null;
let reloadRequested = false;
const listeners = new Set<Listener>();

const setUpdateReady = (worker: ServiceWorker | null) => {
    if (worker) waitingWorker = worker;
    if (updateReady) return;
    updateReady = true;
    listeners.forEach(listener => listener());
};

/** For `useSyncExternalStore`: whether a newer version is ready to load. */
export const subscribeToAppUpdate = (listener: Listener): (() => void) => {
    listeners.add(listener);
    return () => {
        listeners.delete(listener);
    };
};

export const isAppUpdateReady = (): boolean => updateReady;

/** Let the waiting worker take over, then reload into the new version. */
export function applyAppUpdate(): void {
    reloadRequested = true;
    const worker = waitingWorker;
    // Another tab may already have activated the new worker, in which case
    // this page is controlled by it and only needs a reload to load its files.
    if (!worker || worker.state === 'activated' || navigator.serviceWorker?.controller === worker) {
        window.location.reload();
        return;
    }
    worker.postMessage({ type: 'SKIP_WAITING' });
    // `controllerchange` below does the reload. If the worker went away in the
    // meantime (a newer build replaced it), reload anyway so the tap is never
    // a dead button; the next load picks up whatever is waiting.
    window.setTimeout(() => window.location.reload(), 3000);
}

const trackRegistration = (registration: ServiceWorkerRegistration) => {
    // A worker can already be waiting from an earlier visit.
    if (registration.waiting && navigator.serviceWorker.controller) {
        setUpdateReady(registration.waiting);
    }
    registration.addEventListener('updatefound', () => {
        const worker = registration.installing;
        if (!worker) return;
        worker.addEventListener('statechange', () => {
            // With no controller this is the very first install: there is no
            // older version on screen, so nothing to tell anyone.
            if (worker.state === 'installed' && navigator.serviceWorker.controller) {
                setUpdateReady(worker);
            }
        });
    });
};

/**
 * Register the service worker and watch for new builds for as long as the app
 * stays open.
 */
export function watchForAppUpdates(): void {
    if (typeof window === 'undefined' || !('serviceWorker' in navigator)) return;
    // The worker is only generated by `vite build`.
    if (!import.meta.env.PROD) return;

    let hasController = !!navigator.serviceWorker.controller;

    navigator.serviceWorker.addEventListener('controllerchange', () => {
        if (reloadRequested) {
            window.location.reload();
            return;
        }
        // The first claim after a fresh install is not an update.
        if (!hasController) {
            hasController = true;
            return;
        }
        // The user refreshed in another tab. This tab still runs the old
        // JavaScript, so offer the same refresh here instead of reloading
        // under them.
        setUpdateReady(null);
    });

    const register = () => {
        navigator.serviceWorker
            .register(`${import.meta.env.BASE_URL}sw.js`, { scope: import.meta.env.BASE_URL })
            .then(registration => {
                trackRegistration(registration);

                // Browsers only re-check sw.js on navigation. This is an
                // installed PWA that people leave open for days, so poll as
                // well and re-check whenever the tab comes back to the front.
                let lastCheck = Date.now();
                const check = () => {
                    if (document.visibilityState !== 'visible') return;
                    if (Date.now() - lastCheck < MIN_CHECK_INTERVAL_MS) return;
                    lastCheck = Date.now();
                    // Rejects when the device is offline or sw.js 404s
                    // mid-deploy; neither is worth surfacing.
                    registration.update().catch(() => {});
                };
                window.setInterval(check, UPDATE_CHECK_INTERVAL_MS);
                document.addEventListener('visibilitychange', check);
                window.addEventListener('focus', check);
            })
            .catch(() => {
                // No service worker in this context (unsupported scheme in the
                // desktop app, plain http, or blocked by the browser).
            });
    };

    if (document.readyState === 'complete') register();
    else window.addEventListener('load', register, { once: true });
}
