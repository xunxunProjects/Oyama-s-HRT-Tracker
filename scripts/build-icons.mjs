async function svg(weight, name) {
    const file = path.join(assets, weight, weight === 'regular' ? `${name}.svg` : `${name}-${weight}.svg`);
    return fs.readFile(file, 'utf8');
}

/** Every path in the file: its d, and whether it is the duotone wash. */
function paths(text) {
    return [...text.matchAll(/<path\b([^>]*)\/?>/g)].map(m => ({
        d: /\bd="([^"]+)"/.exec(m[1])[1],
        wash: /\bopacity="0?\.2"/.test(m[1]),
    }));
}

const one = list => list.map(p => p.d).join(' ');

const regular = {};
for (const [ours, theirs] of Object.entries(GLYPHS)) regular[ours] = one(paths(await svg('regular', theirs)));
const fill = {};
for (const ours of FILLED) fill[ours] = one(paths(await svg('fill', GLYPHS[ours])));
const duotone = {};
for (const [ours, theirs] of Object.entries(DRAWINGS)) {
    const ps = paths(await svg('duotone', theirs));
    duotone[ours] = { wash: one(ps.filter(p => p.wash)), line: one(ps.filter(p => !p.wash)) };
}

const body = `// Generated by scripts/build-icons.mjs from Phosphor Icons (https://phosphoricons.com),
// MIT License, Copyright (c) 2023 Phosphor Icons. Do not edit by hand: change
// the lists in the script and run it again.
//
// Every path is on Phosphor's 256-unit grid and is drawn filled.

export const REGULAR = ${JSON.stringify(regular, null, 4)} as const;

export const FILL: Partial<Record<keyof typeof REGULAR, string>> = ${JSON.stringify(fill, null, 4)};

export const DUOTONE = ${JSON.stringify(duotone, null, 4)} as const;
`;
// Written as the repo's Prettier would write it, so format:check passes.
